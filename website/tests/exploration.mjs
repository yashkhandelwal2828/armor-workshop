import { launchBrowser, baseURL } from "./browser-support.mjs";
import assert from "node:assert/strict";
const b = await launchBrowser();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
await p.goto(baseURL);
await p.waitForFunction(() => window.workshop?.getState().ready);
await p.click("#explore");
const state = () => p.evaluate(() => window.workshop.getState());
assert((await state()).freeRoam);
let start = (await state()).camera;
await p.keyboard.down("KeyW");
await p.waitForTimeout(700);
await p.keyboard.up("KeyW");
let after = (await state()).camera;
assert(Math.hypot(...after.map((v, i) => v - start[i])) > 0.5);
await p.mouse.move(650, 450);
await p.mouse.down();
await p.mouse.move(900, 470, { steps: 15 });
await p.mouse.up();
start = (await state()).camera;
await p.keyboard.down("KeyE");
await p.waitForTimeout(400);
await p.keyboard.up("KeyE");
assert((await state()).camera[1] > start[1] + 0.2);
await p.screenshot({ path: "test-results/free-roam.png" });
await p.keyboard.press("Escape");
assert.equal((await state()).freeRoam, false);
await p.click("#explore");
await p.click("[data-panel=inventory]");
assert.equal((await state()).freeRoam, false);
await p.waitForTimeout(800);
await p.screenshot({ path: "test-results/shelves-wide.png" });
await p.setViewportSize({ width: 390, height: 844 });
await p.click("#explore");
start = (await state()).camera;
const box = await p.locator("[data-travel=KeyW]").boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
await p.mouse.down();
await p.waitForTimeout(400);
await p.mouse.up();
assert(Math.hypot(...(await state()).camera.map((v, i) => v - start[i])) > 0.2);
await p.screenshot({ path: "test-results/free-roam-mobile.png" });
assert.deepEqual(errors, []);
await b.close();
console.log(
  "Free roam movement, drag, vertical travel, Escape, inventory return and mobile passed",
);
